-- profiles: users see/update their own row, admins see/update everyone's
drop policy if exists "profiles_select_own" on profiles;
create policy "profiles_select_own" on profiles for select
    using (auth.uid() = id);

drop policy if exists "profiles_select_admin" on profiles;
create policy "profiles_select_admin" on profiles for select
    using (public.is_admin());

drop policy if exists "profiles_update_own" on profiles;
create policy "profiles_update_own" on profiles for update
    using (auth.uid() = id)
    with check (auth.uid() = id);

drop policy if exists "profiles_update_admin" on profiles;
create policy "profiles_update_admin" on profiles for update
    using (public.is_admin());

-- Belt-and-braces: even though the admin Users page is the only intended
-- place role changes happen, this trigger stops a non-admin from ever
-- promoting themselves by silently reverting any role change they attempt.
create or replace function public.prevent_role_self_escalation()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    if new.role is distinct from old.role and not public.is_admin() then
        new.role := old.role;
    end if;
    return new;
end;
$$;

drop trigger if exists profiles_guard_role on profiles;

create trigger profiles_guard_role
    before update on profiles
    for each row execute function public.prevent_role_self_escalation();

-- categories: readable by everyone, writable by admins only
drop policy if exists "categories_select_all" on categories;
create policy "categories_select_all" on categories for select
    using (true);

drop policy if exists "categories_write_admin" on categories;
create policy "categories_write_admin" on categories for all
    using (public.is_admin())
    with check (public.is_admin());

-- products: public sees active products, admins see/manage everything
drop policy if exists "products_select_active" on products;
create policy "products_select_active" on products for select
    using (is_active = true);

drop policy if exists "products_select_admin" on products;
create policy "products_select_admin" on products for select
    using (public.is_admin());

drop policy if exists "products_write_admin" on products;
create policy "products_write_admin" on products for all
    using (public.is_admin())
    with check (public.is_admin());

-- wishlist: each user manages only their own rows
drop policy if exists "wishlist_owner" on wishlist;
create policy "wishlist_owner" on wishlist for all
    using (auth.uid() = user_id)
    with check (auth.uid() = user_id);

-- addresses: each user manages only their own rows
drop policy if exists "addresses_owner" on addresses;
create policy "addresses_owner" on addresses for all
    using (auth.uid() = user_id)
    with check (auth.uid() = user_id);

-- analytics_events: anyone (including anonymous visitors) can log an event,
-- only admins can read them back
drop policy if exists "analytics_insert_any" on analytics_events;
create policy "analytics_insert_any" on analytics_events for insert
    with check (true);

drop policy if exists "analytics_select_admin" on analytics_events;
create policy "analytics_select_admin" on analytics_events for select
    using (public.is_admin());

-- ---------- Storage: product images ----------

insert into storage.buckets (id, name, public)
values ('product-images', 'product-images', true)
on conflict (id) do nothing;

drop policy if exists "product_images_public_read" on storage.objects;
create policy "product_images_public_read" on storage.objects for select
    using (bucket_id = 'product-images');

drop policy if exists "product_images_admin_write" on storage.objects;
create policy "product_images_admin_write" on storage.objects for insert
    with check (bucket_id = 'product-images' and public.is_admin());

drop policy if exists "product_images_admin_update" on storage.objects;
create policy "product_images_admin_update" on storage.objects for update
    using (bucket_id = 'product-images' and public.is_admin());

drop policy if exists "product_images_admin_delete" on storage.objects;
create policy "product_images_admin_delete" on storage.objects for delete
    using (bucket_id = 'product-images' and public.is_admin());

