create extension if not exists "uuid-ossp";

-- ---------- Core tables ----------

create table if not exists profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    full_name text,
    email text,
    role text not null default 'user' check (role in ('user', 'admin')),
    created_at timestamptz default now()
);

-- Add the email column if this schema was run before it existed.
alter table profiles add column if not exists email text;

create table if not exists categories (
    id bigint generated by default as identity primary key,
    name text unique not null
);

create table if not exists products (
    id bigint generated by default as identity primary key,
    title text not null,
    description text,
    price numeric(12,2) not null,
    category text,
    category_id bigint references categories(id),
    location text,
    images jsonb default '[]'::jsonb,
    image_url text,
    reseller_link text default '',
    is_active boolean default true,
    created_by uuid references profiles(id),
    created_at timestamptz default now()
);

-- Add new columns to products if they are missing (safe to re-run).
alter table products add column if not exists category text;
alter table products add column if not exists image_url text;
alter table products alter column reseller_link set default '';

create table if not exists wishlist (
    id bigint generated by default as identity primary key,
    user_id uuid references auth.users(id) on delete cascade,
    product_id bigint references products(id) on delete cascade,
    created_at timestamptz default now(),
    unique (user_id, product_id)
);

create table if not exists addresses (
    id bigint generated by default as identity primary key,
    user_id uuid references auth.users(id) on delete cascade,
    line1 text not null,
    line2 text,
    city text not null,
    state text not null,
    pincode text not null,
    is_default boolean default false
);

create table if not exists analytics_events (
    id bigint generated by default as identity primary key,
    event_type text not null check (event_type in ('page_view', 'product_view', 'reseller_click')),
    product_id bigint references products(id) on delete set null,
    user_id uuid references auth.users(id) on delete set null,
    created_at timestamptz default now()
);

