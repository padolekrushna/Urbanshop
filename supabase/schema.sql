-- ---------- Auto-create a profile row whenever someone signs up ----------
-- Also copies their email into profiles so the admin Users page can show it
-- (auth.users isn't readable from the client, profiles is).

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    insert into public.profiles (id, full_name, email, role)
    values (
        new.id,
        coalesce(new.raw_user_meta_data->>'full_name', ''),
        new.email,
        'user'
    );
    return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;

create trigger on_auth_user_created
    after insert on auth.users
    for each row execute function public.handle_new_user();

-- ---------- Admin check helper ----------
-- security definer lets this bypass RLS internally so policies that call it
-- don't recursively re-trigger the RLS check on profiles.

create or replace function public.is_admin()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
    select exists (
        select 1 from public.profiles
        where id = auth.uid() and role = 'admin'
    );
$$;

